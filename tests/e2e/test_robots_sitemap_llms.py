from __future__ import annotations

import re
from pathlib import Path
import xml.etree.ElementTree as ET

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
SITE_URL = "https://mingchen.id.vn"


def _file_for(site_dir: Path, url: str) -> Path:
    """Map a site URL onto the file that serves it inside the built site."""
    if url.startswith(SITE_URL):
        path = url[len(SITE_URL):]
    elif url.startswith("http://mingchen.id.vn"):
        path = url[len("http://mingchen.id.vn"):]
    else:
        path = url

    if path in ("", "/"):
        return site_dir / "index.html"
    path_clean = path.lstrip("/")
    if path_clean.endswith("/"):
        return site_dir / path_clean / "index.html"
    if (site_dir / path_clean).suffix == "":
        return site_dir / path_clean / "index.html"
    return site_dir / path_clean


def test_robots_txt_exists_and_has_required_content(built_site):
    """robots.txt exists in the build with the required directives verbatim."""
    robots_path = built_site / "robots.txt"
    assert robots_path.exists(), f"robots.txt must exist in {built_site}"

    lines = [line.strip() for line in robots_path.read_text(encoding="utf-8").splitlines()]
    assert "User-agent: *" in lines, "robots.txt must contain the exact line 'User-agent: *'"
    assert "Content-Signal: search=yes, ai-input=yes, ai-train=yes" in lines
    assert "Allow: /" in lines, "robots.txt must contain the exact line 'Allow: /'"
    assert f"Sitemap: {SITE_URL}/sitemap.xml" in lines


def test_sitemap_xml_parses_and_urls_match_site_files(built_site):
    """sitemap.xml parses as XML, has unique locs, and every loc is a build file."""
    sitemap_path = built_site / "sitemap.xml"
    assert sitemap_path.exists(), f"sitemap.xml must exist in {built_site}"

    content = sitemap_path.read_text(encoding="utf-8")
    # Parse XML
    try:
        root = ET.fromstring(content)
    except ET.ParseError:
        pytest.fail("sitemap.xml does not parse as valid XML")

    # Find all loc elements (handle namespace, with a non-namespace fallback)
    locs = [url.text for url in root.findall(".//{*}loc")]
    if not locs:
        locs = [url.text for url in root.findall(".//loc")]

    assert locs, "sitemap.xml must contain at least one loc element"

    # Every URL must be emitted exactly once (no duplicated entries)
    assert len(locs) == len(set(locs)), (
        "sitemap.xml has duplicate locs: "
        + ", ".join(sorted(loc for loc in set(locs) if locs.count(loc) > 1))
    )

    # Check no excluded files
    for loc in locs:
        assert "404.html" not in loc
        assert "feed.xml" not in loc
        assert "sitemap.xml" not in loc
        assert "llms.txt" not in loc

    # Paginated list pages generated by jekyll-paginate must be in the sitemap
    paginated = sorted(
        entry.name
        for entry in built_site.iterdir()
        if entry.is_dir() and re.fullmatch(r"page\d+", entry.name)
    )
    for page_dir in paginated:
        assert f"{SITE_URL}/{page_dir}/" in locs, (
            f"paginated page /{page_dir}/ exists in the build but is missing from sitemap.xml"
        )

    # Check each loc resolves to a file in the build
    for loc in locs:
        file_path = _file_for(built_site, loc)
        assert file_path.exists(), f"sitemap loc {loc} should correspond to {file_path}"


def test_sitemap_post_count_matches(built_site):
    """Number of post URLs in sitemap equals number of published posts."""
    sitemap_path = built_site / "sitemap.xml"
    assert sitemap_path.exists()

    content = sitemap_path.read_text(encoding="utf-8")
    try:
        root = ET.fromstring(content)
    except ET.ParseError:
        pytest.fail("sitemap.xml does not parse as valid XML")

    # Published posts are the only URLs carrying a /YYYY/MM/DD/ date segment
    # (pages, tag pages and /pageN/ paginated lists never do).
    locs = [url.text or "" for url in root.findall(".//{*}loc")]
    post_locs = [loc for loc in locs if re.search(r"/\d{4}/\d{2}/\d{2}/", loc)]

    # Count actual published posts in _posts
    posts_dir = REPO_ROOT / "_posts"
    published_posts = []
    if posts_dir.exists():
        for p in posts_dir.glob("*.md"):
            try:
                content = p.read_text(encoding="utf-8")
                # Simple check for published: false
                if "published: false" in content:
                    continue
                published_posts.append(p)
            except Exception:
                published_posts.append(p)
    post_files = published_posts

    assert len(post_locs) == len(post_files), f"sitemap has {len(post_locs)} post URLs but there are {len(post_files)} published posts"


def test_llms_txt_exists_and_urls_resolve(built_site):
    """llms.txt exists and every URL-like token resolves to a file in the build."""
    llms_path = built_site / "llms.txt"
    assert llms_path.exists(), f"llms.txt must exist in {built_site}"

    content = llms_path.read_text(encoding="utf-8")
    # Look for URLs
    urls = re.findall(r"https?://[^\s:]+", content)

    assert urls, "llms.txt should contain URLs"

    for url in urls:
        # Clean trailing punctuation
        url_clean = url.rstrip(".,)")
        if not url_clean.startswith(("https://mingchen.id.vn", "http://mingchen.id.vn")):
            continue  # Skip non-site URLs
        file_path = _file_for(built_site, url_clean)
        assert file_path.exists(), f"llms.txt URL {url_clean} should resolve to {file_path}"
